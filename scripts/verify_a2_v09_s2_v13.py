def _sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def _sha256_file(path):
    return _sha256_bytes(Path(path).read_bytes())


def _plain(value):
    """Recursively convert numpy/torch values into JSON-serialisable ones."""
    if isinstance(value, dict):
        return {str(key): _plain(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(item) for item in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, torch.Tensor):
        return value.detach().cpu().tolist()
    return value


def _rel_error(produced, expected):
    scale = max(abs(float(expected)), 1e-300)
    return abs(float(produced) - float(expected)) / scale


def _within(produced, expected, *, rtol, atol):
    return abs(float(produced) - float(expected)) <= atol + rtol * abs(float(expected))


def _line_of(lines, start_line, needle):
    for offset, line in enumerate(lines):
        if needle in line:
            return start_line + offset
    return None


def _file_line(path, needle):
    lines = Path(path).read_text(encoding='utf-8').splitlines()
    for number, line in enumerate(lines, 1):
        if needle in line:
            return f'{path.relative_to(ROOT)}:{number}'
    return None


def _git(*args):
    try:
        proc = subprocess.run(['git', *args], cwd=str(ROOT), capture_output=True,
                              text=True, check=False)
        return proc.stdout.strip() if proc.returncode == 0 else None
    except OSError:
        return None


def _source_lines(obj):
    """Fresh source lines; tolerate a concurrent editor rewriting the file."""
    import linecache
    import time
    last_error = None
    for _attempt in range(5):
        try:
            filename = inspect.getsourcefile(obj) or inspect.getfile(obj)
            linecache.checkcache(filename)
            return inspect.getsourcelines(obj)
        except OSError as error:  # pragma: no cover - concurrent editor
            last_error = error
            time.sleep(0.05)
    raise last_error


def _locate(obj, needles):
    """Find all needles in freshly read source, retrying across concurrent writes."""
    import time
    lines, start, found = [], 1, {}
    for _attempt in range(5):
        lines, start = _source_lines(obj)
        found = {key: _line_of(lines, start, needle)
                 for key, needle in needles.items()}
        if all(value is not None for value in found.values()):
            break
        time.sleep(0.05)
    return lines, start, found


