# 3. PPO storage: unique (env_id, step) labels through production flattens
# ---------------------------------------------------------------------------
def check_ppo_storage(num_envs=4, time_steps=None):
    time_steps = int(time_steps or s2_runner.ROLLOUT_STEPS)
    off_obs, off_act, off_old, off_adv, off_ret = (1_000_000, 2_000_000,
                                                   3_000_000, 4_000_000,
                                                   5_000_000)
    transitions = []
    for step in range(time_steps):
        obs_value = torch.tensor(
            [[off_obs + 1000 * env + step] * 45 for env in range(num_envs)],
            dtype=torch.float32)
        action_value = torch.tensor(
            [[off_act + 1000 * env + step] * 12 for env in range(num_envs)],
            dtype=torch.float32)
        logp_value = torch.tensor(
            [off_old + 1000 * env + step for env in range(num_envs)],
            dtype=torch.float32)
        transitions.append(dict(obs={'proprio': obs_value,
                                     'history': obs_value[:, None, :].expand(
                                         num_envs, 5, 45).clone()},
                                actions=action_value, log_probs=logp_value))
    advantages = torch.tensor(
        [[off_adv + 1000 * env + step for env in range(num_envs)]
         for step in range(time_steps)], dtype=torch.float32)
    returns = torch.tensor(
        [[off_ret + 1000 * env + step for env in range(num_envs)]
         for step in range(time_steps)], dtype=torch.float32)

    # Exactly the flatten expressions used by S2Trainer.update (s2_train.py).
    flat_obs = {}
    for key in transitions[0]['obs']:
        flat_obs[key] = torch.cat([row['obs'][key] for row in transitions], 0)
    flat_actions = torch.stack([row['actions'] for row in transitions],
                               0).reshape(-1, 12)
    flat_old = s2_train.flatten_time_major_old_logs(transitions)
    flat_adv = advantages.reshape(-1)
    flat_ret = returns.reshape(-1)

    total = time_steps * num_envs
    samples = []
    aligned = True
    for position in range(total):
        env_id = position % num_envs
        step = position // num_envs
        expected = 1000 * env_id + step
        values = dict(
            obs=float(flat_obs['proprio'][position, 0]) - off_obs,
            actions=float(flat_actions[position, 0]) - off_act,
            old_logp=float(flat_old[position]) - off_old,
            advantage=float(flat_adv[position]) - off_adv,
            returns=float(flat_ret[position]) - off_ret)
        ok = all(abs(value - expected) <= 1e-6 for value in values.values())
        aligned = aligned and ok
        samples.append(dict(position=position, env_id=env_id, step=step,
                            expected_label=expected,
                            **{key: int(round(value)) for key, value in values.items()},
                            aligned=bool(ok)))

    # Counter-example: env-major old-logp flatten does not match the time-major
    # obs/action/adv flatten.
    env_major_old = torch.stack(
        [row['log_probs'] for row in transitions], 1).reshape(-1)
    env_major_mismatches = sum(
        1 for position in range(total)
        if abs(float(env_major_old[position]) - off_old
               - (1000 * (position % num_envs) + position // num_envs)) > 1e-6)

    # Logical-minibatch plan + Adam count, mirroring S2Trainer.update.
    plan = s2_runner.logical_minibatch_plan(total)
    per = math.ceil(total / s2_runner.MINIBATCHES)
    adam_updates = 0
    coverage = [0] * total
    minibatch_ids = [None] * total
    for _epoch in range(s2_runner.EPOCHS):
        for start in range(0, total, per):
            index = list(range(start, min(start + per, total)))
            minibatch_id = adam_updates
            adam_updates += 1
            micro = math.ceil(len(index) / s2_runner.MICROBATCH_MAX)
            for position in index:
                coverage[position] += 1
                minibatch_ids[position] = dict(
                    adam_update=minibatch_id, epoch=_epoch, microbatches=micro)
    expected_adam = s2_runner.EPOCHS * s2_runner.MINIBATCHES
    passed = bool(aligned and adam_updates == expected_adam
                  and all(count == s2_runner.EPOCHS for count in coverage)
                  and plan['logical_size'] == per
                  and plan['adam_updates_per_epoch'] == s2_runner.MINIBATCHES
                  and env_major_mismatches > 0)
    return dict(
        name='ppo_storage',
        passed=passed,
        num_envs=num_envs,
        time_steps=time_steps,
        samples_total=total,
        alignment=dict(
            all_aligned=bool(aligned),
            ordering='time-major: position = step * num_envs + env_id',
            per_sample=samples),
        env_major_counterexample=dict(
            mismatches=int(env_major_mismatches),
            note='env-major old-logp flatten differs from time-major obs/action/'
                 'advantage/return flatten, so time-major is required'),
        minibatch_plan=dict(plan),
        expected_adam_updates=expected_adam,
        measured_adam_updates=int(adam_updates),
        per_epoch_minibatches=per,
        coverage_per_sample=dict(min=min(coverage), max=max(coverage),
                                 expected=s2_runner.EPOCHS),
        minibatch_ids_per_sample=minibatch_ids,
    )


