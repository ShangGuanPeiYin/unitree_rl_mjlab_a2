class _ResetFailsEnv(s2_train_env.S2FakeTrainEnv):
    def reset(self):
        raise RuntimeError('injected env.reset failure')


class _StepFailsEnv(s2_train_env.S2FakeTrainEnv):
    def __init__(self, *, fail_at, **kwargs):
        super().__init__(**kwargs)
        self.calls = 0
        self.fail_at = int(fail_at)

    def step(self, actions):
        if self.calls >= self.fail_at:
            raise RuntimeError('injected env.step failure')
        self.calls += 1
        return super().step(actions)


class _UpdateFailsTrainer(s2_train.S2Trainer):
    def update(self, transitions, advantages, returns):
        raise RuntimeError('injected update failure')


def _run_settlement_scenario(kind, tmpdir):
    ledger, ledger_path = _new_ledger(tmpdir)
    num_envs = 2
    samples_per_rollout = num_envs * s2_runner.ROLLOUT_STEPS
    budget = s2_train.S2LearningBudget(
        ledger, obligation_id='learning_S2_1',
        samples_per_rollout=samples_per_rollout)
    error = None
    save_error = None
    checkpoint_path = Path(tmpdir) / 'checkpoint.pt'
    learning_samples = None

    if kind == 'reset_failure':
        env = _ResetFailsEnv(num_envs=num_envs,
                             role_plan=s2_train_env.build_role_plan(num_envs))
        trainer = _fake_trainer(ledger, num_envs=num_envs, env=env)
        expected_executed = 0
        try:
            trainer.train_rollout(budget=budget)
        except RuntimeError as exc:
            error = str(exc)
    elif kind == 'step_failure':
        executed_steps = 3
        env = _StepFailsEnv(fail_at=executed_steps, num_envs=num_envs,
                            role_plan=s2_train_env.build_role_plan(num_envs))
        trainer = _fake_trainer(ledger, num_envs=num_envs, env=env)
        expected_executed = num_envs * executed_steps
        try:
            trainer.train_rollout(budget=budget)
        except RuntimeError as exc:
            error = str(exc)
    elif kind == 'update_failure':
        env = s2_train_env.S2FakeTrainEnv(
            num_envs=num_envs, role_plan=s2_train_env.build_role_plan(num_envs))
        trainer = _UpdateFailsTrainer(
            model=V09ActorCritic(), env=env, ledger=ledger, device='cpu',
            attempt_id='v13', learning_rate=3e-5)
        expected_executed = samples_per_rollout
        try:
            trainer.train_rollout(budget=budget)
        except RuntimeError as exc:
            error = str(exc)
    elif kind == 'checkpoint_failure':
        env = s2_train_env.S2FakeTrainEnv(
            num_envs=num_envs, role_plan=s2_train_env.build_role_plan(num_envs))
        trainer = _fake_trainer(ledger, num_envs=num_envs, env=env)
        expected_executed = samples_per_rollout
        result = trainer.train_rollout(budget=budget)
        learning_samples = int(trainer.learning_samples)
        # Physical checkpoint-write failure: target path is a directory.
        checkpoint_path.mkdir(parents=True)
        try:
            trainer.save(checkpoint_path)
        except OSError as exc:
            save_error = f'{type(exc).__name__}: {exc}'
        if save_error is None:
            raise AssertionError('checkpoint write failure was not injected')
    else:
        raise ValueError(f'unknown scenario {kind}')

    events = _read_ledger_events(ledger_path)
    reserve = sum(event['samples'] for event in events
                  if event['kind'] == 'obligation_reserve')
    commit = sum(event['samples'] for event in events
                 if event['kind'] == 'obligation_commit')
    release = sum(event['samples'] for event in events
                  if event['kind'] == 'obligation_release')
    state = ledger.state()['learning_obligations']['learning_S2_1']
    amounts_ok = (reserve == samples_per_rollout
                  and commit == expected_executed
                  and release == samples_per_rollout - expected_executed
                  and state['spent'] == expected_executed
                  and state['reserved'] == 0)
    return dict(
        scenario=kind, error=error, checkpoint_error=save_error,
        reservation=samples_per_rollout,
        physically_executed_samples=expected_executed,
        reserve=reserve, commit=commit, release=release,
        ledger_spent=state['spent'], ledger_reserved=state['reserved'],
        learning_samples=learning_samples,
        events=events,
        passed=bool(amounts_ok))


