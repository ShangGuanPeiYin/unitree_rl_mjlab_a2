def check_g_level(handcalc_path):
    data = json.loads(Path(handcalc_path).read_text(encoding='utf-8'))
    expectation = data['g_level_sequence']
    ramp_steps = int(expectation['ramp_steps'])
    rows = []
    passed = True
    gx = 0.1          # JSON note: pitch uses gx=0.1
    v_heading = 0.8   # JSON note
    c_exec = 0.5      # JSON note
    for row in expectation['rows']:
        step, t0 = int(row['step']), int(row['t0'])
        produced = s2_rewards.g_level_at(step, t0, ramp_steps=ramp_steps)
        pitch = produced * gx ** 2
        overspeed = produced * max(v_heading - c_exec - 0.15, 0.0) ** 2
        ok = (abs(produced - float(row['g_level'])) <= 1e-12
              and abs(pitch - float(row['pitch_term'])) <= 1e-12
              and abs(overspeed - float(row['overspeed_term'])) <= 1e-12)
        passed = passed and ok
        rows.append(dict(
            step=step, t0=t0,
            expected=dict(g_level=float(row['g_level']),
                          pitch_term=float(row['pitch_term']),
                          overspeed_term=float(row['overspeed_term'])),
            produced=dict(g_level=float(produced), pitch_term=float(pitch),
                          overspeed_term=float(overspeed)),
            source=dict(g_level='s2_rewards.g_level_at',
                        pitch_term='documented_formula g_level*gx^2 (JSON note)',
                        overspeed_term='documented_formula g_level*max(v-request-0.15,0)^2'),
            passed=bool(ok)))

    # Production CPU lifecycle adapter: drive S2Lifecycle through the same
    # six steps and read its g_level.  This is the lifecycle seam used by the
    # real training adapter (s2_train_real builds it from the plan rows).
    lifecycle = s2_lifecycle.S2Lifecycle(
        task=['stairs_walk'], post_distance=[5.0], speed=[0.5],
        stop_mode=['none'], legacy=[False], front=[0.0], spawn_x=[-1.0],
        completion_steps=[1000])
    lifecycle_rows = []
    for step in range(1, 42):
        top_signal = step >= 10
        failure = step >= 41
        out = lifecycle.update(
            local_x=np.array([1.0]), top_signal=np.array([top_signal]),
            four_feet=np.array([True]), body_ok=np.array([True]),
            quality_ok=np.array([True]), failure=np.array([failure]),
            timeout=np.array([False]))
        if step in (9, 10, 11, 34, 35, 41):
            expected_row = next(r for r in expectation['rows'] if int(r['step']) == step)
            produced = float(out['g_level'][0])
            ok = abs(produced - float(expected_row['g_level'])) <= 1e-12
            passed = passed and ok
            lifecycle_rows.append(dict(step=step, produced_g_level=produced,
                                       expected_g_level=float(expected_row['g_level']),
                                       passed=bool(ok),
                                       lifecycle_g_step=int(lifecycle.g_step[0])))

    # Report (do not judge) the trainer's inline adapter contract: it gates
    # g_ready on four-foot support + body margin + ~failure, with no top flag.
    adapter_line = _file_line(
        ROOT / 'src/tasks/velocity/v09/s2_train_real.py',
        'g_ready = (support.all(-1)')
    lifecycle_line = _file_line(
        ROOT / 'src/tasks/velocity/v09/s2_lifecycle.py',
        'g_ready = self.top & four_feet & body_ok')
    return dict(
        name='g_level_sequence',
        passed=bool(passed),
        source='production s2_rewards.g_level_at + s2_lifecycle.S2Lifecycle (pure CPU)',
        ramp_steps=ramp_steps,
        control_dt=s2_train_real_control_dt(),
        tolerance=dict(rtol=1e-12, atol=1e-12),
        rows=rows,
        lifecycle_ramp=lifecycle_rows,
        formula='g_level = 0 if t0<0 or step<t0 else clamp((step-t0)/25, 0, 1); '
                'not-ready resets t0 to -1 -> g_level 0',
        adapter_contract_note=dict(
            lifecycle_g_ready=lifecycle_line,
            trainer_inline_g_ready=adapter_line,
            difference='training adapter omits the lifecycle `top` term in g_ready; '
                       'reported for review, not judged by the frozen g_level JSON'),
    )


