@contextmanager
def _patched_digest(module, digest):
    class _Hash:
        def hexdigest(self):
            return digest

    original = module.hashlib
    module.hashlib = type('PatchedHashlib', (), {'sha256': staticmethod(
        lambda _data: _Hash())})
    try:
        yield
    finally:
        module.hashlib = original


