def _guarded(name, function):
    """Run one check; a crash becomes an explicit failed check, not a lost run."""
    try:
        return function()
    except Exception as error:  # noqa: BLE001 - evidence must record any failure
        return dict(name=name, passed=False,
                    error=f'{type(error).__name__}: {error}',
                    traceback=__import__('traceback').format_exc())


def build_report(*, handcalc_path=DEFAULT_HANDCALC, tmpdir=None):
    checks = {}
    checks['handcalc_13_cases'] = _guarded(
        'handcalc_13_cases', lambda: check_handcalc(handcalc_path))
    checks['g_level_sequence'] = _guarded(
        'g_level_sequence', lambda: check_g_level(handcalc_path))
    checks['ppo_storage'] = _guarded('ppo_storage', check_ppo_storage)
    checks['gae_boundary'] = _guarded('gae_boundary', check_gae_boundary)
    checks['flat_anchor'] = _guarded(
        'flat_anchor', lambda: check_flat_anchor(handcalc_path))

    if tmpdir is None:
        with tempfile.TemporaryDirectory(prefix='v13_evidence_') as temp:
            checks['exception_settlement'] = _guarded(
                'exception_settlement',
                lambda: check_exception_settlement(temp))
            checks['r1_rejection'] = _guarded(
                'r1_rejection', lambda: check_r1_rejection(temp))
    else:
        base = Path(tmpdir)
        base.mkdir(parents=True, exist_ok=True)
        checks['exception_settlement'] = _guarded(
            'exception_settlement',
            lambda: check_exception_settlement(base / 'settlement'))
        checks['r1_rejection'] = _guarded(
            'r1_rejection', lambda: check_r1_rejection(base / 'r1'))

    order = ['handcalc_13_cases', 'g_level_sequence', 'ppo_storage',
             'gae_boundary', 'exception_settlement', 'r1_rejection',
             'flat_anchor']
    ordered = {name: checks[name] for name in order}
    all_passed = all(check['passed'] for check in ordered.values())

    handcalc_sha = _sha256_file(handcalc_path)
    production_files = [
        'src/tasks/velocity/v09/s2_rewards.py',
        'src/tasks/velocity/v09/s2_train.py',
        'src/tasks/velocity/v09/s2_train_real.py',
        'src/tasks/velocity/v09/s2_runner.py',
        'src/tasks/velocity/v09/s2_loss.py',
        'src/tasks/velocity/v09/s2_r1.py',
        'src/tasks/velocity/v09/s2_ledger.py',
        'src/tasks/velocity/v09/s2_train_env.py',
        'src/tasks/velocity/v09/s2_lifecycle.py',
        'scripts/train_a2_v09_s2.py',
        'scripts/run_a2_v09_s2_gate.py',
    ]
    return _plain(dict(
        schema='a2_v09_s2_v13_cpu_evidence_v1',
        generated_at=datetime.now(timezone.utc).isoformat(),
        role='CPU-side evidence pack for S2.1 plan v13 §6.1 items 1-6',
        scope=dict(
            gpu=False, mjlab=False, mujoco=False, training=False, gate=False,
            production_files_modified=False,
            ledger_writes='temporary ledgers only; logs/a2_v09/s2/ledger.jsonl untouched'),
        repo=dict(root=str(ROOT), branch=_git('rev-parse', '--abbrev-ref', 'HEAD'),
                  head=_git('rev-parse', 'HEAD'),
                  production_file_sha256={
                      path: _sha256_file(ROOT / path) for path in production_files}),
        environment=dict(
            python=platform.python_version(), numpy=np.__version__,
            torch=torch.__version__, platform=platform.platform()),
        inputs=dict(
            handcalc=dict(path=str(Path(handcalc_path).relative_to(ROOT)),
                          sha256=handcalc_sha),
            verify_script=dict(
                path=str(Path(__file__).resolve().relative_to(ROOT)),
                sha256=_sha256_file(__file__))),
        checks=ordered,
        check_order=order,
        all_passed=bool(all_passed),
        blocked_real_backend=[
            'Run A: two consecutive sampling blocks on the real 512/1024 backend',
            'Run B: real representative samples per coverage matrix',
            'Run C: action/command alignment on a real stop sequence',
            'Run D: §5.4 anchor with Frozen6400Teacher (old 48x32 map) on real weights',
            'Run E: resource/budget re-check on the fixed execution stack',
        ],
        not_verified=[
            'no GPU execution, no mjlab/MuJoCo physics, no real rollout',
            'no anchor gradient through real weights; teacher=None in the current CLI',
            'no real per-env terminated/truncated/failure_class capture',
            'no real action/command chain sample (a_request/a_applied/c_exec)',
            'hand-calc terms are exercised through compute_reward_batch, not the '
            'full S2TrainEnv._s2_reward frame assembly (needs mjlab)',
        ],
    ))


def _print_summary(report):
    width = 26
    print('=' * 92)
    print(f"{'CHECK':<{width}} {'RESULT':<7} KEY MEASUREMENT")
    print('-' * 92)
    checks = report['checks']
    for name in report['check_order']:
        check = checks[name]
        if 'error' in check:
            print(f"{name:<{width}} {'FAIL':<7} ERROR {check['error']}")
            continue
        if name == 'handcalc_13_cases':
            metric = (f"{check['case_count']} cases, max|dtotal|="
                      f"{check['max_abs_error']['total']:.3e}, "
                      f"sha_ok={check['input_sha256_matches_plan']}")
        elif name == 'g_level_sequence':
            values = [row['produced']['g_level'] for row in check['rows']]
            metric = f"g_level={values}"
        elif name == 'ppo_storage':
            metric = (f"{check['samples_total']} samples aligned="
                      f"{check['alignment']['all_aligned']}, adam="
                      f"{check['measured_adam_updates']}/"
                      f"{check['expected_adam_updates']}")
        elif name == 'gae_boundary':
            metric = (f"{len(check['rows'])} cases, max err="
                      f"{max(max(row['max_abs_error'].values()) for row in check['rows']):.2e}, "
                      f"static_ok={check['collect_rollout_contract']['static_ok']}")
        elif name == 'exception_settlement':
            metric = ', '.join(
                f"{row['scenario']}={row['commit']}/{row['physically_executed_samples']}"
                for row in check['scenarios'])
        elif name == 'r1_rejection':
            metric = (f"4 dummies rejected="
                      f"{all(row['rejected'] for row in check['dummy_file_rejection'])}, "
                      f"wiring={check['wiring']['ok']}")
        elif name == 'flat_anchor':
            metric = (f"examples={check['examples_passed']}, "
                      f"trainer_mode={check['trainer_aggregation']['mode']}")
        else:
            metric = ''
        print(f"{name:<{width}} {'PASS' if check['passed'] else 'FAIL':<7} {metric}")
    print('-' * 92)
    print(f"ALL PASSED: {report['all_passed']}")
    print('=' * 92)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--handcalc', type=Path, default=DEFAULT_HANDCALC)
    parser.add_argument('--tmpdir', type=Path, default=None,
                        help='optional scratch directory (temp dir by default)')
    args = parser.parse_args(argv)

    report = build_report(handcalc_path=args.handcalc, tmpdir=args.tmpdir)
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n',
                      encoding='utf-8')
    report['evidence_path'] = str(output)
    report['evidence_sha256'] = _sha256_file(output)
    _print_summary(report)
    print(f"evidence: {output}")
    print(f"sha256:   {report['evidence_sha256']}")
    return 0 if report['all_passed'] else 1


