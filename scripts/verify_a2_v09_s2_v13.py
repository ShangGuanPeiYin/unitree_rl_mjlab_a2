def _handcalc_frame(case_input):
    frame = {}
    missing = set(HANDCALC_INPUT_MAP) - set(case_input)
    if missing:
        raise ValueError(f'handcalc case missing input keys: {sorted(missing)}')
    extra = set(case_input) - set(HANDCALC_INPUT_MAP)
    if extra:
        raise ValueError(f'handcalc case has unmapped input keys: {sorted(extra)}')
    for source_key, frame_key in HANDCALC_INPUT_MAP.items():
        value = case_input[source_key]
        if source_key == 'phase':
            frame[frame_key] = [str(value)]
        else:
            frame[frame_key] = [value]
    return frame


def check_handcalc(handcalc_path):
    handcalc_path = Path(handcalc_path)
    data = json.loads(handcalc_path.read_text(encoding='utf-8'))
    file_sha = _sha256_file(handcalc_path)

    declared_sha = None
    if PLAN_DOC.exists():
        match = re.search(r'SHA256\s*`([0-9a-f]{64})`', PLAN_DOC.read_text(encoding='utf-8'))
        if match:
            declared_sha = match.group(1)

    cases = []
    worst = dict(total=0.0, continuous=0.0, forward_progress=0.0)
    max_abs_per_term = {}
    max_rel_per_term = {}
    v07_rows = []
    all_passed = True

    for name in data['cases']:
        case = data['cases'][name]
        frame = _handcalc_frame(case['input'])
        produced = s2_rewards.compute_reward_batch(frame)
        expected = case['expected_s2']
        case_passed = True

        terms = {}
        produced_names = set(produced['terms'])
        expected_names = set(expected['terms'])
        term_count_ok = (produced_names == expected_names
                         == set(s2_rewards.WEIGHTS) and len(expected_names) == 20)
        if not term_count_ok:
            case_passed = False
        for term in sorted(expected_names):
            got = float(produced['terms'][term][0])
            exp = float(expected['terms'][term])
            ok = _within(got, exp, **TOL_FLOAT64)
            case_passed = case_passed and ok
            abs_error = abs(got - exp)
            rel_error = _rel_error(got, exp)
            max_abs_per_term[term] = max(max_abs_per_term.get(term, 0.0), abs_error)
            max_rel_per_term[term] = max(max_rel_per_term.get(term, 0.0), rel_error)
            terms[term] = dict(expected=exp, produced=got, abs_error=abs_error,
                               rel_error=rel_error, passed=bool(ok))

        scalars = {}
        for key, produced_key, expected_key in (
                ('continuous', 'continuous', 'continuous'),
                ('forward_progress', 'forward_progress', 'forward'),
                ('total', 'total', 'total')):
            got = float(produced[produced_key][0])
            exp = float(expected[expected_key])
            ok = _within(got, exp, **TOL_FLOAT64)
            case_passed = case_passed and ok
            abs_error = abs(got - exp)
            worst[key] = max(worst[key], abs_error)
            scalars[key] = dict(expected=exp, produced=got, abs_error=abs_error,
                                rel_error=_rel_error(got, exp), passed=bool(ok))

        discrete = {}
        for key, produced_key, expected_key in (
                ('column', 'column', 'column'),
                ('cruise', 'cruise', 'cruise'),
                ('top', 'top', 'top'),
                ('success', 'success', 'success'),
                ('failure', 'failure', 'failure')):
            if key == 'column':
                got = int(produced[produced_key][0])
                exp = int(expected[expected_key])
            else:
                got = bool(produced[produced_key][0])
                exp = bool(expected[expected_key])
            ok = got == exp
            case_passed = case_passed and ok
            discrete[key] = dict(expected=exp, produced=got, passed=bool(ok))

        v07 = None
        if 'expected_v07' in case:
            expected_v07 = case['expected_v07']
            shared = sorted(set(expected_v07['terms']) & set(expected_names))
            term_diffs = {
                term: dict(
                    expected_v07=float(expected_v07['terms'][term]),
                    expected_s2=float(expected['terms'][term]),
                    produced_s2=float(produced['terms'][term][0]),
                    s2_minus_v07=float(expected['terms'][term])
                    - float(expected_v07['terms'][term]))
                for term in shared}
            produced_total = float(produced['total'][0])
            v07 = dict(
                expected_v07_total=float(expected_v07['total']),
                expected_s2_total=float(expected['total']),
                json_s2_minus_v07=float(case.get('s2_minus_v07', expected['total']
                                                 - expected_v07['total'])),
                produced_s2_minus_v07=produced_total - float(expected_v07['total']),
                shared_terms=term_diffs,
                note='expected_v07 is reported for contrast only; it is NOT a judge')
            v07_rows.append(dict(case=name, **v07))
            if abs(v07['json_s2_minus_v07'] - v07['produced_s2_minus_v07']) > 1e-9:
                # informational mismatch is reported; it does not judge the S2 reward
                v07['mismatch_vs_production'] = True

        cases.append(dict(
            case=name, purpose=case.get('purpose'),
            terms=terms, scalars=scalars, discrete=discrete,
            term_count_ok=bool(term_count_ok), v07=v07,
            passed=bool(case_passed)))
        all_passed = all_passed and case_passed

    if declared_sha is not None and declared_sha != file_sha:
        all_passed = False

    return dict(
        name='handcalc_13_cases',
        passed=bool(all_passed),
        production_function='src.tasks.velocity.v09.s2_rewards.compute_reward_batch',
        production_dtype='float64 (numpy asarray(dtype=float)); no float32 cast',
        tolerance_reference='plan §2.2 float64 row: rtol=1e-12, atol=1e-12 '
                            '(float32 row rtol=2e-6/atol=2e-7/total_atol=2e-6 unused here)',
        tolerance=dict(TOL_FLOAT64),
        input_file=str(handcalc_path.relative_to(ROOT)),
        input_sha256=file_sha,
        declared_sha256_in_plan=declared_sha,
        input_sha256_matches_plan=(None if declared_sha is None
                                   else bool(declared_sha == file_sha)),
        frame_key_map=dict(HANDCALC_INPUT_MAP),
        cases=cases,
        case_count=len(cases),
        max_abs_error=dict(worst),
        max_abs_error_per_term=dict(sorted(max_abs_per_term.items())),
        max_rel_error_per_term=dict(sorted(max_rel_per_term.items())),
        v07_difference_report=v07_rows,
        v07_note='v07 expectations are reported only to show the old-chain gap '
                 'and v07 is NOT a judge; the S2 hand-calc JSON is the sole judge.',
    )


